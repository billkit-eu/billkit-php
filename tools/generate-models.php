<?php

declare(strict_types=1);

/**
 * Generate the typed response classes in src/Model/ from BillKit's public
 * OpenAPI document.
 *
 *     php tools/generate-models.php           write src/Model/
 *     php tools/generate-models.php --check   exit 1 if src/Model/ is stale
 *     php tools/generate-models.php --spec=path/to/openapi.json
 *
 * The spec defaults to the monorepo copy the docs site publishes,
 * docs-public/public/openapi/latest.json. tests/GeneratedModelsTest.php runs
 * the same generator and fails when the committed files differ from its
 * output, so a spec change cannot land without its classes.
 *
 * What is generated, and why:
 *
 * - One `final` class per response schema reachable from a route the SDK
 *   wraps, named after the schema without its `Response` suffix. Each known
 *   field is a `public readonly` property typed from the schema, and every
 *   one is nullable and always initialised: `null` when the payload lacks the
 *   field or carries a value of the wrong type. A stored event snapshot is
 *   served as it was recorded, so a field a later API adds (even a required
 *   one) is absent from older events, and reading a property must never
 *   throw `\Error` because of it.
 * - `MAP_FIELDS` lists the JSON-object fields (`metadata`, ...), so that
 *   `json_encode()` writes an empty one as `{}` rather than PHP's `[]`.
 * - `x-extensible-enum` values become class constants
 *   (`Subscription::STATUS_ACTIVE`). The property stays a `string`, because
 *   these enums are open: the API may add a value, and a closed PHP enum
 *   would make that a crash instead of a value to ignore.
 * - `Event` (from `EventResponse`) is the base of every event, and one
 *   subclass per webhook event schema narrows `data` (`SubscriptionUpdatedEvent`
 *   carries a `Subscription`).
 * - `Registry` maps `object` and event `type` values to classes, for the
 *   places where only the payload says what it is.
 *
 * - `RequestMaps` names the request-body fields each route types as a JSON
 *   object, so the transport sends an empty one as `{}` (an empty PHP array
 *   would encode as the list `[]`, which the API refuses for a map).
 *
 * Request bodies are not otherwise generated: params stay plain arrays.
 */

namespace BillKit\Tools;

final class ModelGenerator
{
    public const DEFAULT_SPEC = __DIR__ . '/../../../docs-public/public/openapi/latest.json';

    public const OUT_DIR = __DIR__ . '/../src/Model';

    public const HEADER_MARK = 'Generated by tools/generate-models.php';

    /**
     * Routes the SDK deliberately does not wrap; their schemas are not generated.
     * Console-only routes are not listed: the public document already leaves
     * them out, so the spec is the filter.
     */
    private const SKIPPED_PATHS = ['/v1/ping', '/v1/events/stream'];

    /** Class names that are not "schema name minus Response". */
    private const RENAMES = [
        'EventResponse' => 'Event',
        'CouponValidateResponse' => 'CouponValidation',
        'PortalTenantTheme-Output' => 'PortalTenantTheme',
    ];

    /** Fields every event schema shares, declared once on `Event`. */
    private const EVENT_FIELDS = ['id', 'object', 'type', 'created', 'livemode', 'data', 'previous_attributes'];

    /** @var array<string, array<string, mixed>> */
    private array $schemas;

    /** @var array<string, string> event type => schema name */
    private array $webhookSchemas = [];

    /**
     * @param array<string, mixed> $spec
     */
    public function __construct(private readonly array $spec)
    {
        $this->schemas = $spec['components']['schemas'];
    }

    public static function fromFile(string $path): self
    {
        $raw = file_get_contents($path);
        if ($raw === false) {
            throw new \RuntimeException("cannot read {$path}");
        }

        return new self(json_decode($raw, true, 512, JSON_THROW_ON_ERROR));
    }

    /**
     * @return array<string, string> file name (relative to src/Model) => contents
     */
    public function generate(): array
    {
        $names = $this->reachableSchemas();
        $files = [];
        $objects = [];
        $events = [];

        foreach ($names as $name) {
            $class = $this->className($name);
            if ($name === 'EventResponse') {
                $files['Event.php'] = $this->eventBaseClass($name);
            } elseif (in_array($name, $this->webhookSchemas, true)) {
                [$type, $source] = $this->typedEventClass($name);
                $events[$type] = $class;
                $files["{$class}.php"] = $source;

                continue;
            } else {
                $files["{$class}.php"] = $this->modelClass($name);
            }
            $object = $this->schemas[$name]['properties']['object']['const'] ?? null;
            if (is_string($object) && $object !== 'event') {
                // Two schemas may share an object name (a session and its
                // revocation receipt). The shorter class name is the object
                // itself, and is the one a payload of unknown shape becomes.
                if (!isset($objects[$object]) || strlen($class) < strlen($objects[$object])) {
                    $objects[$object] = $class;
                }
            }
        }

        ksort($objects);
        ksort($events);
        $files['Registry.php'] = $this->registryClass($objects, $events);
        $files['RequestMaps.php'] = $this->requestMapsClass();
        ksort($files);

        return $files;
    }

    /**
     * Response schemas reachable from the wrapped routes and the webhooks,
     * with list envelopes replaced by their item schemas.
     *
     * @return list<string>
     */
    private function reachableSchemas(): array
    {
        $roots = [];
        foreach ($this->spec['paths'] as $path => $ops) {
            if (in_array($path, self::SKIPPED_PATHS, true)) {
                continue;
            }
            foreach ($ops as $method => $op) {
                if (!is_array($op) || !isset($op['responses'])) {
                    continue;
                }
                foreach ($op['responses'] as $status => $response) {
                    if (!str_starts_with((string) $status, '2')) {
                        continue;
                    }
                    $ref = $response['content']['application/json']['schema']['$ref'] ?? null;
                    if (is_string($ref)) {
                        $roots[] = self::refName($ref);
                    }
                }
            }
        }
        foreach ($this->spec['webhooks'] ?? [] as $type => $hook) {
            $ref = $hook['post']['requestBody']['content']['application/json']['schema']['$ref'] ?? null;
            if (is_string($ref)) {
                $this->webhookSchemas[$type] = self::refName($ref);
                $roots[] = self::refName($ref);
            }
        }

        $seen = [];
        $walk = function (string $name) use (&$walk, &$seen): void {
            if (isset($seen[$name])) {
                return;
            }
            $schema = $this->schemas[$name] ?? throw new \RuntimeException("unknown schema {$name}");
            if (str_starts_with($name, 'ListResponse_')) {
                $walk(self::refName($schema['properties']['data']['items']['$ref']));

                return;
            }
            $seen[$name] = true;
            foreach ($schema['properties'] ?? [] as $prop) {
                foreach (self::refsIn($prop) as $ref) {
                    $walk($ref);
                }
            }
        };
        foreach ($roots as $root) {
            $walk($root);
        }

        $names = array_keys($seen);
        sort($names);

        return $names;
    }

    private function className(string $schema): string
    {
        if (isset(self::RENAMES[$schema])) {
            return self::RENAMES[$schema];
        }
        if (str_ends_with($schema, 'Response')) {
            return substr($schema, 0, -strlen('Response'));
        }
        if (preg_match('/^[A-Z][A-Za-z0-9]*$/', $schema) !== 1) {
            throw new \RuntimeException("schema {$schema} has no PHP class name; add it to RENAMES");
        }

        return $schema;
    }

    private function modelClass(string $name): string
    {
        $schema = $this->schemas[$name];
        $class = $this->className($name);

        $constants = [];
        $object = $schema['properties']['object']['const'] ?? null;
        if (is_string($object)) {
            $constants[] = "    public const OBJECT_NAME = '{$object}';";
        }
        $properties = [];
        $hydrate = [];
        $nested = [];
        $maps = [];
        foreach ($schema['properties'] ?? [] as $field => $prop) {
            $type = $this->resolve($prop);
            foreach ($this->enumValues($prop) as $value) {
                $constants[] = sprintf(
                    "    public const %s = '%s';",
                    self::constName($field . '_' . $value),
                    $value,
                );
            }
            $properties[] = $this->propertyDecl($field, $prop, $type);
            $hydrate[] = $this->hydrateLine($field, $type);
            if ($type['nested'] !== null) {
                $nested[$field] = $type['nested'];
            }
            if (self::isMap($type)) {
                $maps[] = $field;
            }
        }
        self::assertUnique($constants, $class);

        $body = [];
        if ($constants !== []) {
            $body[] = implode("\n", $constants);
        }
        if ($nested !== []) {
            $body[] = $this->nestedConst($nested);
        }
        if ($maps !== []) {
            $body[] = self::mapConst($maps);
        }
        if ($properties !== []) {
            $body[] = implode("\n\n", $properties);
            $body[] = self::constructor($hydrate);
        }

        return $this->file(
            $this->classDoc($name, $schema),
            "final class {$class} extends BillKitObject",
            $body,
            ['BillKit\\BillKitObject'],
        );
    }

    private function eventBaseClass(string $name): string
    {
        $schema = $this->schemas[$name];
        $properties = [];
        $hydrate = [];
        $nested = [];
        $maps = [];
        foreach ($schema['properties'] as $field => $prop) {
            if ($field === 'data') {
                $properties[] = "    /**\n     * The object the event is about, as it stood when the event was recorded.\n"
                    . "     * A typed subclass narrows it (a `Subscription` on\n"
                    . "     * `SubscriptionUpdatedEvent`); on an event type this SDK version does\n"
                    . "     * not know, it is the model its `object` names, or a plain\n"
                    . "     * `BillKitObject`. Null only when the payload carried no object.\n     *\n"
                    . "     * @var TData|null\n     */\n"
                    . '    public readonly ?BillKitObject $data;';
                $hydrate[] = "        \$value = \$this->raw('data');\n"
                    . "        /** @var TData|null \$data */\n"
                    . "        \$data = \$value instanceof BillKitObject ? \$value : null;\n"
                    . '        $this->data = $data;';

                continue;
            }
            $type = $this->resolve($prop);
            $properties[] = $this->propertyDecl($field, $prop, $type);
            $hydrate[] = $this->hydrateLine($field, $type);
            if ($type['nested'] !== null) {
                $nested[$field] = $type['nested'];
            }
            if (self::isMap($type)) {
                $maps[] = $field;
            }
        }

        $body = [
            "    public const OBJECT_NAME = 'event';\n\n"
            . "    /**\n     * The data class a typed subclass decodes `data` into; null here.\n     *\n"
            . "     * @var class-string<BillKitObject>|null\n     */\n"
            . '    protected const DATA_CLASS = null;',
            $this->nestedConst($nested) . ($maps !== [] ? "\n\n" . self::mapConst($maps) : ''),
            implode("\n\n", $properties),
            <<<'PHP'
                    /**
                     * Decode an event payload into its typed class when this SDK version
                     * knows its `type` (`SubscriptionUpdatedEvent` for `subscription.updated`),
                     * and into a plain `Event` otherwise. An unknown type is never an error.
                     *
                     * @param array<array-key, mixed> $values
                     */
                    public static function constructFrom(array $values): static
                    {
                        $class = static::class;
                        if ($class === self::class && is_string($values['type'] ?? null)) {
                            $class = Registry::eventClass($values['type']) ?? self::class;
                        }
                        /** @var static $event */
                        $event = new $class($values);

                        return $event;
                    }

                    /**
                     * @param array<string, mixed> $values
                     *
                     * @return array<string, mixed>
                     */
                    protected static function convertValues(array $values): array
                    {
                        $values = parent::convertValues($values);
                        $data = $values['data'] ?? null;
                        if (is_array($data)) {
                            $class = static::DATA_CLASS ?? Registry::objectClass($data);
                            $values['data'] = $class::constructFrom($data);
                        }

                        return $values;
                    }
                PHP,
            self::constructor($hydrate),
        ];

        $doc = "/**\n * An event: something that happened in your account.\n *\n"
            . " * Returned by `\$client->events` and by {@see \\BillKit\\Webhooks::verifySignature()}.\n"
            . " * Each type this SDK version knows has a subclass whose `data` is typed;\n"
            . " * route on `instanceof` or on `type`, and ignore what you do not handle:\n *\n"
            . " *     if (\$event instanceof SubscriptionUpdatedEvent) {\n"
            . " *         \$event->data?->status;\n *     }\n *\n"
            . " * Generated from the `{$name}` schema.\n *\n"
            . " * @template-covariant TData of BillKitObject = BillKitObject\n */";

        return $this->file($doc, 'class Event extends BillKitObject', $body, ['BillKit\\BillKitObject']);
    }

    /**
     * @return array{0: string, 1: string}
     */
    private function typedEventClass(string $name): array
    {
        $schema = $this->schemas[$name];
        $type = $schema['properties']['type']['const'] ?? throw new \RuntimeException("{$name} has no type const");
        foreach (array_keys($schema['properties']) as $field) {
            if (!in_array($field, self::EVENT_FIELDS, true)) {
                throw new \RuntimeException("{$name}.{$field} is not a field Event declares; teach the generator");
            }
        }
        $dataRef = $schema['properties']['data']['$ref'] ?? throw new \RuntimeException("{$name}.data is not a \$ref");
        $dataClass = $this->className(self::refName($dataRef));
        $class = $this->className($name);

        $doc = "/**\n * `{$type}`.\n *\n" . $this->wrapDoc($this->description($schema), ' * ')
            . " *\n * Generated from the `{$name}` schema.\n *\n * @extends Event<{$dataClass}>\n */";
        $body = [
            "    public const TYPE = '{$type}';\n\n    protected const DATA_CLASS = {$dataClass}::class;",
        ];

        return [$type, $this->file($doc, "final class {$class} extends Event", $body, [])];
    }

    /**
     * @param array<string, string> $objects
     * @param array<string, string> $events
     */
    private function registryClass(array $objects, array $events): string
    {
        $objectLines = [];
        foreach ($objects as $object => $class) {
            $objectLines[] = "        '{$object}' => {$class}::class,";
        }
        $eventLines = [];
        foreach ($events as $type => $class) {
            $eventLines[] = "        '{$type}' => {$class}::class,";
        }

        $doc = "/**\n * Which class a payload decodes into, when only the payload says.\n *\n"
            . " * @internal\n */";
        $body = [
            "    /** @var array<string, class-string<BillKitObject>> */\n    public const OBJECTS = [\n"
            . implode("\n", $objectLines) . "\n    ];",
            "    /** @var array<string, class-string<Event>> */\n    public const EVENTS = [\n"
            . implode("\n", $eventLines) . "\n    ];",
            <<<'PHP'
                    /**
                     * The class for a payload's `object`, or the plain base class for one
                     * this SDK version does not know.
                     *
                     * @param array<array-key, mixed> $data
                     *
                     * @return class-string<BillKitObject>
                     */
                    public static function objectClass(array $data): string
                    {
                        $object = $data['object'] ?? null;

                        return is_string($object) ? (self::OBJECTS[$object] ?? BillKitObject::class) : BillKitObject::class;
                    }

                    /**
                     * The typed class for an event `type`, or null for one this SDK version
                     * does not know.
                     *
                     * @return class-string<Event>|null
                     */
                    public static function eventClass(string $type): ?string
                    {
                        return self::EVENTS[$type] ?? null;
                    }
                PHP,
        ];

        return $this->file($doc, 'final class Registry', $body, ['BillKit\\BillKitObject']);
    }

    /**
     * The request-body fields each route types as a JSON object, straight
     * from the document, so an empty one is sent as `{}`. PHP has one array
     * type for both shapes and `json_encode([])` picks the list, which the
     * API refuses for a map (`"metadata":[]` is a 400). Lists that are
     * genuinely lists (`tiers`, `enabled_events`) are not named, so they
     * keep their `[]`.
     *
     * Nested objects are named by dotted path. `FALLBACK` is for a route a
     * newer API added: the top-level names that are an object wherever the
     * document uses them, and never anything else.
     */
    private function requestMapsClass(): string
    {
        $routes = [];
        $objectNames = [];
        $otherNames = [];
        foreach ($this->spec['paths'] as $path => $ops) {
            foreach ($ops as $method => $op) {
                $schema = is_array($op) ? ($op['requestBody']['content']['application/json']['schema'] ?? null) : null;
                if (!is_array($schema)) {
                    continue;
                }
                $paths = [];
                foreach ($this->bodyProperties($schema) as $field => $prop) {
                    if ($this->isObjectSchema($prop)) {
                        $objectNames[$field] = true;
                    } else {
                        $otherNames[$field] = true;
                    }
                }
                $this->collectObjectPaths($schema, '', $paths, []);
                sort($paths);
                // Every route with a body is listed, the ones with no object
                // field too, so only a route the document lacks falls back.
                $routes[strtoupper((string) $method) . ' ' . $path] = $paths;
            }
        }
        ksort($routes);
        $fallback = array_keys(array_diff_key($objectNames, $otherNames));
        sort($fallback);

        $quote = static fn (array $keys): string => implode(', ', array_map(static fn (string $k): string => "'{$k}'", $keys));
        $lines = [];
        foreach ($routes as $route => $paths) {
            $lines[] = "        '{$route}' => [" . $quote($paths) . '],';
        }

        $doc = "/**\n * The request-body fields each route types as a JSON object, from the OpenAPI\n"
            . " * document, so that an empty one is sent as `{}` rather than PHP's `[]`.\n *\n"
            . " * @internal\n */";
        $body = [
            "    /** @var array<string, list<string>> */\n    public const ROUTES = [\n"
            . implode("\n", $lines) . "\n    ];",
            "    /**\n     * Top-level fields that are an object on every route that has them; used\n"
            . "     * for a route the document does not list.\n     *\n     * @var list<string>\n     */\n"
            . '    public const FALLBACK = [' . $quote($fallback) . '];',
            <<<'PHP'
                    /**
                     * `$body` with every empty array at an object-typed path replaced by
                     * an empty `\stdClass`, which `json_encode()` writes as `{}`. A
                     * non-empty array is left alone: it already encodes as an object
                     * when its keys are strings, and a list there is the caller's
                     * mistake for the API to name. `$path` is the request path with its
                     * ids already percent-encoded, so no id contains a `/`.
                     *
                     * @param array<array-key, mixed> $body
                     *
                     * @return array<array-key, mixed>
                     */
                    public static function apply(string $method, string $path, array $body): array
                    {
                        foreach (self::paths($method, $path) as $dotted) {
                            $body = self::emptyToObject($body, explode('.', $dotted));
                        }

                        return $body;
                    }

                    /**
                     * @param array<array-key, mixed> $value
                     * @param list<string>            $segments
                     *
                     * @return array<array-key, mixed>
                     */
                    private static function emptyToObject(array $value, array $segments): array
                    {
                        $key = array_shift($segments);
                        if ($key === null || !array_key_exists($key, $value)) {
                            return $value;
                        }
                        if ($segments === []) {
                            if ($value[$key] === []) {
                                $value[$key] = new \stdClass();
                            }

                            return $value;
                        }
                        if (is_array($value[$key]) && $value[$key] !== []) {
                            $value[$key] = self::emptyToObject($value[$key], $segments);
                        }

                        return $value;
                    }

                    /**
                     * The object paths for a concrete path, matching a literal route
                     * before a templated one, else the fallback.
                     *
                     * @return list<string>
                     */
                    private static function paths(string $method, string $path): array
                    {
                        $exact = self::ROUTES["{$method} {$path}"] ?? null;
                        if ($exact !== null) {
                            return $exact;
                        }
                        $segments = explode('/', $path);
                        foreach (self::ROUTES as $route => $paths) {
                            [$routeMethod, $template] = explode(' ', $route, 2);
                            if ($routeMethod !== $method) {
                                continue;
                            }
                            $parts = explode('/', $template);
                            if (count($parts) !== count($segments)) {
                                continue;
                            }
                            $match = true;
                            foreach ($parts as $i => $part) {
                                if ($part !== $segments[$i] && !str_starts_with($part, '{')) {
                                    $match = false;

                                    break;
                                }
                            }
                            if ($match) {
                                return $paths;
                            }
                        }

                        return self::FALLBACK;
                    }
                PHP,
        ];

        return $this->file($doc, 'final class RequestMaps', $body, []);
    }

    /**
     * The named properties of a request schema, through `$ref` and
     * `anyOf`/`oneOf`/`allOf`.
     *
     * @param array<string, mixed> $schema
     *
     * @return array<string, array<string, mixed>>
     */
    private function bodyProperties(array $schema): array
    {
        $schema = $this->deref($schema);
        $props = [];
        foreach (['anyOf', 'oneOf', 'allOf'] as $combinator) {
            foreach ($schema[$combinator] ?? [] as $option) {
                $props += $this->bodyProperties($option);
            }
        }
        foreach ($schema['properties'] ?? [] as $name => $prop) {
            $props[(string) $name] = $prop;
        }

        return $props;
    }

    /**
     * Whether a property is a JSON object in any of its forms (a nullable
     * object is `anyOf: [object, null]`).
     *
     * @param array<string, mixed> $prop
     */
    private function isObjectSchema(array $prop): bool
    {
        $prop = $this->deref($prop);
        foreach (['anyOf', 'oneOf', 'allOf'] as $combinator) {
            foreach ($prop[$combinator] ?? [] as $option) {
                if ($this->isObjectSchema($option)) {
                    return true;
                }
            }
        }

        return ($prop['type'] ?? null) === 'object' || isset($prop['properties']) || isset($prop['additionalProperties']);
    }

    /**
     * @param array<string, mixed> $schema
     * @param list<string>         $paths
     * @param array<string, true>  $seen   schema names on the current branch, against cycles
     */
    private function collectObjectPaths(array $schema, string $prefix, array &$paths, array $seen): void
    {
        if (isset($schema['$ref'])) {
            $name = self::refName($schema['$ref']);
            if (isset($seen[$name])) {
                return;
            }
            $seen[$name] = true;
        }
        foreach ($this->bodyProperties($schema) as $field => $prop) {
            if (!$this->isObjectSchema($prop)) {
                continue;
            }
            $dotted = $prefix === '' ? $field : "{$prefix}.{$field}";
            $paths[] = $dotted;
            foreach ($this->objectOptions($prop) as $option) {
                $this->collectObjectPaths($option, $dotted, $paths, $seen);
            }
        }
        $paths = array_values(array_unique($paths));
    }

    /**
     * The object-typed alternatives of a property, still carrying their `$ref`.
     *
     * @param array<string, mixed> $prop
     *
     * @return list<array<string, mixed>>
     */
    private function objectOptions(array $prop): array
    {
        $options = [];
        foreach (['anyOf', 'oneOf', 'allOf'] as $combinator) {
            foreach ($prop[$combinator] ?? [] as $option) {
                $options = array_merge($options, $this->objectOptions($option));
            }
        }
        if ($this->isObjectSchema($prop) && !isset($prop['anyOf']) && !isset($prop['oneOf']) && !isset($prop['allOf'])) {
            $options[] = $prop;
        }

        return $options;
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return array<string, mixed>
     */
    private function deref(array $schema): array
    {
        $guard = 0;
        while (isset($schema['$ref']) && $guard++ < 32) {
            $schema = $this->schemas[self::refName($schema['$ref'])] ?? throw new \RuntimeException("unknown schema {$schema['$ref']}");
        }

        return $schema;
    }

    /**
     * @param array<string, mixed> $prop
     *
     * @return array{php: string, doc: ?string, expr: string, nullable: bool, nested: string|array{0: string}|null}
     */
    private function resolve(array $prop): array
    {
        // Every property is nullable, required or not: a stored event
        // snapshot is served as recorded, so it can lack a field the schema
        // now requires.
        $nullable = true;
        if (isset($prop['anyOf'])) {
            $options = [];
            foreach ($prop['anyOf'] as $option) {
                if (($option['type'] ?? null) === 'null') {
                    $nullable = true;
                } else {
                    $options[] = $option;
                }
            }
            if (count($options) !== 1) {
                return ['php' => 'mixed', 'doc' => null, 'expr' => '$this->raw(%s)', 'nullable' => true, 'nested' => null];
            }
            $prop = $options[0];
        }

        if (isset($prop['$ref'])) {
            $class = $this->className(self::refName($prop['$ref']));

            return [
                'php' => $class,
                'doc' => null,
                'expr' => "self::asObject(\$this->raw(%s), {$class}::class)",
                'nullable' => $nullable,
                'nested' => $class,
            ];
        }

        $scalar = static fn (string $php, string $fn): array => [
            'php' => $php,
            'doc' => null,
            'expr' => "self::{$fn}(\$this->raw(%s))",
            'nullable' => $nullable,
            'nested' => null,
        ];

        return match ($prop['type'] ?? null) {
            'string' => $scalar('string', 'asString'),
            'integer' => $scalar('int', 'asInt'),
            'number' => $scalar('float', 'asFloat'),
            'boolean' => $scalar('bool', 'asBool'),
            'array' => $this->resolveArray($prop, $nullable),
            'object' => [
                'php' => 'array',
                'doc' => ($prop['additionalProperties']['type'] ?? null) === 'string'
                    ? 'array<string, string>'
                    : 'array<string, mixed>',
                'expr' => ($prop['additionalProperties']['type'] ?? null) === 'string'
                    ? 'self::asStringMap($this->raw(%s))'
                    : 'self::asMap($this->raw(%s))',
                'nullable' => $nullable,
                'nested' => null,
            ],
            null => ['php' => 'mixed', 'doc' => null, 'expr' => '$this->raw(%s)', 'nullable' => true, 'nested' => null],
            default => throw new \RuntimeException('unhandled schema type ' . json_encode($prop)),
        };
    }

    /**
     * @param array<string, mixed> $prop
     *
     * @return array{php: string, doc: ?string, expr: string, nullable: bool, nested: string|array{0: string}|null}
     */
    private function resolveArray(array $prop, bool $nullable): array
    {
        $items = $prop['items'] ?? [];
        if (isset($items['$ref'])) {
            $class = $this->className(self::refName($items['$ref']));

            return [
                'php' => 'array',
                'doc' => "list<{$class}>",
                'expr' => "self::asObjectList(\$this->raw(%s), {$class}::class)",
                'nullable' => $nullable,
                'nested' => [$class],
            ];
        }

        return match ($items['type'] ?? null) {
            'string' => [
                'php' => 'array',
                'doc' => 'list<string>',
                'expr' => 'self::asStringList($this->raw(%s))',
                'nullable' => $nullable,
                'nested' => null,
            ],
            'integer' => [
                'php' => 'array',
                'doc' => 'list<int>',
                'expr' => 'self::asIntList($this->raw(%s))',
                'nullable' => $nullable,
                'nested' => null,
            ],
            default => throw new \RuntimeException('unhandled array items ' . json_encode($prop)),
        };
    }

    /**
     * @param array<string, mixed>                                                                         $prop
     * @param array{php: string, doc: ?string, expr: string, nullable: bool, nested: string|array{0: string}|null} $type
     */
    private function propertyDecl(string $field, array $prop, array $type): string
    {
        $php = $type['php'] === 'mixed' ? 'mixed' : ($type['nullable'] ? '?' : '') . $type['php'];
        $lines = [];
        $description = $this->description($prop);
        if ($description !== '') {
            $lines[] = rtrim($this->wrapDoc($description, '     * '), "\n");
        }
        if ($type['doc'] !== null) {
            if ($lines !== []) {
                $lines[] = '     *';
            }
            $lines[] = '     * @var ' . $type['doc'] . ($type['nullable'] ? '|null' : '');
        }

        $doc = '';
        if ($lines !== []) {
            $doc = "    /**\n" . implode("\n", $lines) . "\n     */\n";
        }

        return $doc . "    public readonly {$php} \${$field};";
    }

    /**
     * @param array{php: string, doc: ?string, expr: string, nullable: bool, nested: string|array{0: string}|null} $type
     */
    private function hydrateLine(string $field, array $type): string
    {
        // Always assigned, so reading the property never throws: a field
        // that is missing or of the wrong type is null, and the raw value
        // stays readable as $obj['field'].
        return "        \$this->{$field} = " . sprintf($type['expr'], "'{$field}'") . ';';
    }

    /**
     * Whether a resolved type is a JSON object decoded into a PHP array.
     *
     * @param array{php: string, doc: ?string, expr: string, nullable: bool, nested: string|array{0: string}|null} $type
     */
    private static function isMap(array $type): bool
    {
        return str_starts_with($type['expr'], 'self::asMap(') || str_starts_with($type['expr'], 'self::asStringMap(');
    }

    /**
     * @param list<string> $fields
     */
    private static function mapConst(array $fields): string
    {
        return "    protected const MAP_FIELDS = ['" . implode("', '", $fields) . "'];";
    }

    /**
     * @param array<string, string|array{0: string}> $nested
     */
    private function nestedConst(array $nested): string
    {
        $lines = [];
        foreach ($nested as $field => $class) {
            $lines[] = is_array($class)
                ? "        '{$field}' => [{$class[0]}::class],"
                : "        '{$field}' => {$class}::class,";
        }

        return "    protected const NESTED = [\n" . implode("\n", $lines) . "\n    ];";
    }

    /**
     * @param array<string, mixed> $prop
     *
     * @return list<string>
     */
    private function enumValues(array $prop): array
    {
        $candidates = [$prop];
        foreach ($prop['anyOf'] ?? [] as $option) {
            $candidates[] = $option;
        }
        if (isset($prop['items'])) {
            $candidates[] = $prop['items'];
        }
        foreach ($candidates as $candidate) {
            if (isset($candidate['x-extensible-enum'])) {
                return $candidate['x-extensible-enum'];
            }
        }

        return [];
    }

    /**
     * @param array<string, mixed> $schema
     */
    private function classDoc(string $name, array $schema): string
    {
        $description = $this->description($schema);
        $doc = "/**\n";
        if ($description !== '') {
            $doc .= $this->wrapDoc($description, ' * ') . " *\n";
        }

        return $doc . " * Generated from the `{$name}` schema.\n */";
    }

    /**
     * @param array<string, mixed> $schema
     */
    private function description(array $schema): string
    {
        $text = $schema['description'] ?? '';
        if (!is_string($text)) {
            return '';
        }
        // The API's docstrings use reStructuredText double backticks.
        $text = str_replace(['``', '*/'], ['`', '* /'], trim($text));

        return preg_replace('/\s+/', ' ', $text) ?? $text;
    }

    private function wrapDoc(string $text, string $prefix): string
    {
        if ($text === '') {
            return '';
        }
        $wrapped = wordwrap($text, 100 - strlen($prefix), "\n", false);
        $out = '';
        foreach (explode("\n", $wrapped) as $line) {
            $out .= rtrim($prefix . $line) . "\n";
        }

        return $out;
    }

    /**
     * @param list<string> $body
     * @param list<string> $uses
     */
    private function file(string $doc, string $declaration, array $body, array $uses): string
    {
        $out = "<?php\n\n// " . self::HEADER_MARK . " from the BillKit OpenAPI document.\n"
            . "// Do not edit by hand: change the generator or the API, then regenerate.\n\n"
            . "declare(strict_types=1);\n\nnamespace BillKit\\Model;\n\n";
        if ($uses !== []) {
            sort($uses);
            foreach ($uses as $use) {
                $out .= "use {$use};\n";
            }
            $out .= "\n";
        }

        return $out . $doc . "\n" . $declaration . "\n{\n" . implode("\n\n", $body) . "\n}\n";
    }

    /**
     * @param list<string> $assignments
     */
    private static function constructor(array $assignments): string
    {
        return "    /**\n     * @param array<array-key, mixed> \$values the decoded JSON object\n     */\n"
            . "    public function __construct(array \$values = [])\n    {\n"
            . "        parent::__construct(\$values);\n"
            . implode("\n", $assignments) . "\n    }";
    }

    private static function constName(string $raw): string
    {
        return strtoupper(trim((string) preg_replace('/[^A-Za-z0-9]+/', '_', $raw), '_'));
    }

    /**
     * @param list<string> $constants
     */
    private static function assertUnique(array $constants, string $class): void
    {
        $names = array_map(static fn (string $line): string => explode(' = ', $line)[0], $constants);
        if (count($names) !== count(array_unique($names))) {
            throw new \RuntimeException("{$class}: two enum values map to the same constant name");
        }
    }

    private static function refName(string $ref): string
    {
        return substr($ref, strlen('#/components/schemas/'));
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return list<string>
     */
    private static function refsIn(array $schema): array
    {
        $refs = [];
        if (isset($schema['$ref'])) {
            $refs[] = self::refName($schema['$ref']);
        }
        foreach ($schema['anyOf'] ?? [] as $option) {
            $refs = array_merge($refs, self::refsIn($option));
        }
        if (isset($schema['items'])) {
            $refs = array_merge($refs, self::refsIn($schema['items']));
        }

        return $refs;
    }
}

/**
 * Write (or with $check, compare) src/Model/. Returns the names of the files
 * that differ, were missing or are stale.
 *
 * @return list<string>
 */
function billkit_generate_models(string $specPath, bool $check): array
{
    $files = ModelGenerator::fromFile($specPath)->generate();
    $outDir = ModelGenerator::OUT_DIR;
    $changed = [];

    foreach ($files as $name => $contents) {
        $path = "{$outDir}/{$name}";
        if (!is_file($path) || file_get_contents($path) !== $contents) {
            $changed[] = $name;
            if (!$check) {
                if (!is_dir($outDir)) {
                    mkdir($outDir, 0o755, true);
                }
                file_put_contents($path, $contents);
            }
        }
    }
    foreach (glob("{$outDir}/*.php") ?: [] as $path) {
        $name = basename($path);
        if (!isset($files[$name]) && str_contains((string) file_get_contents($path), ModelGenerator::HEADER_MARK)) {
            $changed[] = $name;
            if (!$check) {
                unlink($path);
            }
        }
    }
    sort($changed);

    return $changed;
}

if (PHP_SAPI === 'cli' && realpath((string) ($_SERVER['SCRIPT_FILENAME'] ?? '')) === __FILE__) {
    $check = in_array('--check', $argv, true);
    $spec = ModelGenerator::DEFAULT_SPEC;
    foreach ($argv as $arg) {
        if (str_starts_with($arg, '--spec=')) {
            $spec = substr($arg, strlen('--spec='));
        }
    }
    $changed = billkit_generate_models($spec, $check);
    if ($changed === []) {
        fwrite(STDOUT, "src/Model is up to date.\n");
        exit(0);
    }
    fwrite(STDOUT, ($check ? 'Stale' : 'Wrote') . ': ' . implode(', ', $changed) . "\n");
    exit($check ? 1 : 0);
}
